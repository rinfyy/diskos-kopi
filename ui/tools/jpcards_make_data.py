# Builds ui/jpcards_data.c and the character lists for the fonts.
# Sources: open-anki-jlpt-decks (MIT; JLPT lists from tanos.co.uk) and kanji-data (MIT; KANJIDIC, CC BY-SA 4.0, EDRDG).
import csv, json, sys, re, unicodedata
dl, out_c, out_chars = sys.argv[1], sys.argv[2], sys.argv[3]
ASCIIFY = {'\u2018':"'", '\u2019':"'", '\u201c':'"', '\u201d':'"', '\u2026':'...', '\u2013':'-', '\u2014':'-', '\u00a0':' '}
def asc(s):
    for a,b in ASCIIFY.items(): s = s.replace(a,b)
    return s.strip()
def cstr(s): return '"' + s.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n') + '"'
def kata(s): return ''.join(chr(ord(c)+0x60) if 'ぁ' <= c <= 'ゖ' else c for c in s)
def meaning_short(m, n=3, cap=64):
    parts = [p.strip() for p in re.split(r'[,;]', asc(m)) if p.strip()]
    outp = []
    for p in parts:
        if len(', '.join(outp+[p])) > cap: break
        outp.append(p)
        if len(outp) >= n: break
    return ', '.join(outp) if outp else asc(m)[:cap]
cards = {}
for lv in (5, 4):
    rows = list(csv.DictReader(open(f'{dl}/open-anki-jlpt-decks/src/n{lv}.csv', encoding='utf-8')))
    seen = set(); deck = []
    for r in rows:
        e, rd = r['expression'].strip(), r['reading'].strip()
        key = (e, rd)
        if not e or key in seen: continue
        seen.add(key)
        deck.append((e, rd if rd != e else '', meaning_short(r['meaning'])))
    cards[f'VOCAB_N{lv}'] = deck
k = json.load(open(f'{dl}/kanji-data/kanji.json', encoding='utf-8'))
for lv in (5, 4):
    deck = []
    for c, v in sorted(((c, v) for c, v in k.items() if v.get('jlpt_new') == lv), key=lambda cv: (cv[1].get('freq') or 9999, cv[1]['strokes'])):
        ms = [m for m in v['meanings'] if 'radical' not in m.lower() and '(no.' not in m and '**' not in m]
        mean = meaning_short(', '.join(ms[:4]) or ', '.join(v['meanings']), 3, 48)
        on = []
        for x in v['readings_on'] or []:
            y = kata(x.replace('-', '').replace('.', ''))
            if y and y not in on: on.append(y)
        kun = []
        for x in v['readings_kun'] or []:
            x = x.replace('-', '')
            if '.' in x: a, b = x.split('.', 1); x = f'{a}({b})'
            if x and x not in kun: kun.append(x)
        deck.append((c, '、'.join(on[:3]), '、'.join(kun[:3]), mean))
    cards[f'KANJI_N{lv}'] = deck
with open(out_c, 'w', encoding='utf-8') as f:
    f.write('/* SPDX-License-Identifier: CC-BY-SA-4.0 (the kanji data, from KANJIDIC) AND MIT (the vocabulary lists) */\n')
    f.write('/* jpcards_data.c - generated by make_data.py: do not edit. Vocabulary: open-anki-jlpt-decks (MIT, Jamie Sinclair),\n'
            ' * whose JLPT lists are Jonathan Waller\'s (tanos.co.uk). Kanji: kanji-data (MIT, David Gouveia) from KANJIDIC\n'
            ' * (Electronic Dictionary Research and Development Group, CC BY-SA 4.0); JLPT levels as there. */\n')
    f.write('#include "jpcards.h"\n')
    for name, deck in cards.items():
        f.write(f'const jp_card_t JP_{name}[] = {{\n')
        for t in deck:
            if name.startswith('VOCAB'): f.write(f'    {{ {cstr(t[0])}, {cstr(t[1])}, NULL, {cstr(t[2])} }},\n')
            else: f.write(f'    {{ {cstr(t[0])}, {cstr(t[1])}, {cstr(t[2])}, {cstr(t[3])} }},\n')
        f.write('};\n')
        f.write(f'const int JP_{name}_N = {len(deck)};\n')
# characters for the fonts
big = ''.join(t[0] for t in cards['KANJI_N5'] + cards['KANJI_N4'])
words = set(); small = set()
for name in ('VOCAB_N5', 'VOCAB_N4'):
    for t in cards[name]:
        words.update(c for c in t[0] if ord(c) > 0x7e); small.update(c for c in t[1] if ord(c) > 0x7e)
for t in cards['KANJI_N5'] + cards['KANJI_N4']: small.update(c for c in t[1] + t[2] if ord(c) > 0x7e)
kana = [chr(c) for c in list(range(0x3041, 0x3097)) + list(range(0x30A1, 0x30FB)) + [0x30FC, 0x3001, 0x3002, 0x30FB, 0xFF5E, 0x301C]]
small.update(kana); words.update(kana)
json.dump({'big': big, 'words': ''.join(sorted(words)), 'small': ''.join(sorted(small))}, open(out_chars, 'w', encoding='utf-8'), ensure_ascii=False)
print({k: len(v) for k, v in cards.items()}, 'big', len(big), 'words', len(words), 'small', len(small))
